// Disaster-recovery script: rebuilds a D1 database from the Google Sheets backup.
// Use this only if Cloudflare/D1 data is lost — Sheets is the fallback source of truth.
//
// Usage:
//   node scripts/restore-from-sheets.mjs
//   wrangler d1 execute punch-fuel-log --remote --file=restore.sql
//
// Deliberately a local CLI script, not a REST endpoint: a public "restore" route
// would let anyone overwrite D1 on demand, which is not a risk worth taking for a
// disaster-recovery path that's only ever needed manually.

import { writeFileSync } from 'node:fs';

const APPS_SCRIPT_URL = process.env.APPS_SCRIPT_URL
  || 'https://script.google.com/macros/s/AKfycbxmJpCuFho22A5EMWAITzEPHwO6rXCakb9MkX-cjVR0-4GFvyo5KCr3jD5qf_Iueqql9Q/exec';

const FUEL_COLUMNS = ['id', 'bunk', 'date', 'startKM', 'endKM', 'incomingKM', 'remainingKM', 'fuelAmount', 'fuelRate', 'fuelQty', 'projected'];
const TRIP_COLUMNS = ['id', 'Fuel_Id', 'Date', 'StartKM', 'EndKM', 'Distance', 'ToGoKM', 'Diff', 'Notes'];

function sqlValue(v) {
  if (v === null || v === undefined || v === '') return 'NULL';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
}

async function fetchSheet(sheetName) {
  const url = new URL(APPS_SCRIPT_URL);
  url.searchParams.set('action', 'get');
  url.searchParams.set('sheet', sheetName);
  const res = await fetch(url.toString());
  if (!res.ok) throw new Error(`Failed to fetch ${sheetName}: HTTP ${res.status}`);
  const body = await res.json();
  if (!body.success) throw new Error(body.error || `Failed to fetch ${sheetName}`);
  return body.data || [];
}

function buildInserts(tableName, columns, rows) {
  return rows
    .filter(row => row.id)
    .map(row => {
      const values = columns.map(col => sqlValue(row[col])).join(', ');
      return `INSERT INTO ${tableName} (${columns.join(', ')}) VALUES (${values});`;
    })
    .join('\n');
}

const [entries, trips] = await Promise.all([
  fetchSheet('Sheet1'),
  fetchSheet('Trips'),
]);

const sql = [
  '-- Generated by scripts/restore-from-sheets.mjs — restores D1 from the Google Sheets backup.',
  '-- Run migrations/0001_init.sql first if this is a fresh database.',
  'DELETE FROM fuel_entries;',
  'DELETE FROM trips;',
  buildInserts('fuel_entries', FUEL_COLUMNS, entries),
  buildInserts('trips', TRIP_COLUMNS, trips),
  '',
].join('\n');

writeFileSync('restore.sql', sql);
console.log(`Wrote restore.sql: ${entries.length} fuel entries, ${trips.length} trips.`);
console.log('Apply with: wrangler d1 execute punch-fuel-log --remote --file=restore.sql');
